async function checkWheel(page: Page, name: string) {
  const canvas = page.getByRole('application', { name })
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox()
  if (!box) throw new Error('Canvas ausente')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  const before = await page.evaluate(() => scrollY)
  await page.mouse.wheel(0, 180)
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before)
  await canvas.scrollIntoViewIfNeeded()
  const nextBox = await canvas.boundingBox()
  if (!nextBox) throw new Error('Canvas ausente')
  await page.mouse.move(nextBox.x + nextBox.width / 2, nextBox.y + nextBox.height / 2)
  const scroll = await page.evaluate(() => scrollY)
  await page.keyboard.down('Control'); await page.mouse.wheel(0, -240); await page.keyboard.up('Control')
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scroll)
}

