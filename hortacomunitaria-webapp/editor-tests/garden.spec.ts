test('geometria distingue sobreposição, contato, contorno côncavo e cruzamento', () => {
  const sector = { id: 's', name: 'Setor', role: 'sector' as const, shape: 'rectangle' as const, x: 1, y: 1, width: 5, height: 5, rotationDeg: 0 }
  expect(elementsOverlap(sector, { ...sector, x: 5, role: 'bed' })).toBe(true)
  expect(elementsOverlap(sector, { ...sector, x: 6, role: 'bed' })).toBe(false)
  expect(validBoundary([{ x: 0, y: 0 }, { x: 5, y: 5 }, { x: 0, y: 5 }, { x: 5, y: 0 }])).toBe(false)
  const boundary = [{ x: 0, y: 0 }, { x: 10, y: 0 }, { x: 10, y: 3 }, { x: 3, y: 3 }, { x: 3, y: 10 }, { x: 0, y: 10 }]
  expect(validBoundary(boundary)).toBe(true)
  expect(boundaryContainsElement(boundary, { ...sector, width: 1, height: 1 })).toBe(true)
  expect(boundaryContainsElement(boundary, sector)).toBe(false)
})

async function openEditor(page: Page) {
  const garden = { id: 'garden-test', name: 'Horta sem medidas', isActive: true, institutionalAreaM2: null, operationalAreaM2: null, experimentalAreaM2: null }
  let saved: LayoutSnapshot = { version: 0, savedAt: null, layout: null }
  await page.route('**/api/v1/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/layout')) {
      if (route.request().method() === 'PUT') { const data = route.request().postDataJSON(); saved = { version: saved.version + 1, savedAt: '2026-10-25T01:00:00Z', layout: data.layout } }
      return route.fulfill({ json: saved })
    }
    const items = path.endsWith('/gardens') || path.endsWith('/gardens/catalog') ? [garden] : []
    return route.fulfill({ json: path.endsWith('/gardens/garden-test') ? garden : { items, page: 1, pageSize: 100, totalCount: items.length, totalPages: 1, hasNextPage: false, hasPreviousPage: false } })
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/hortas/garden-test/horta/interativa')
  await expect(page.getByRole('heading', { name: 'Mapa interativo da horta' })).toBeVisible()
}

async function point(page: Page, x: number, y: number) {
  await page.getByRole('application').scrollIntoViewIfNeeded()
  const box = await page.getByRole('application').boundingBox()
  if (!box) throw new Error('Canvas ausente')
  const scale = Math.min(box.width - 64, box.height - 64) / 20
  return { x: box.x + (box.width - scale * 20) / 2 + x * scale, y: box.y + (box.height - scale * 20) / 2 + y * scale }
}

async function draw(page: Page, x1: number, y1: number, x2: number, y2: number) {
  const a = await point(page, x1, y1), b = await point(page, x2, y2)
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 5 }); await page.mouse.up()
}

