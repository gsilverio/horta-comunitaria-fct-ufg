test('canteiro permite definir a planta, cadastrar espécie e registrar o plantio no mesmo contexto', async ({ page, request }) => {
  const { garden, sector, prefix } = await context(request)
  const bed = await post(request, `${prefix}/beds`, { name: 'Canteiro da entrada' })
  let response = await request.post(`${api()}${prefix}/beds/${bed.id}/configurations`, { data: { cultivableAreaM2: 6, validFrom: today(), expectedBedVersion: 1 } })
  expect(response.status()).toBe(201)
  response = await request.post(`${api()}${prefix}/beds/${bed.id}/sector-assignments`, { data: { sectorId: sector.id, validFrom: today(), expectedBedVersion: 2 } })
  expect(response.status()).toBe(201)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`/hortas/${garden.id}/horta/canteiros/${bed.id}`)
  await expect(page.getByText('Nenhum cultivo cadastrado', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Adicionar cultivo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'O que será plantado?', exact: true })).toBeVisible()
  await expect(page.locator('select[name="bedId"]')).toHaveCount(0)
  await page.getByLabel('Área ocupada (m²)').fill('3')
  await page.getByRole('button', { name: 'Cadastrar espécie', exact: true }).click()
  await page.getByLabel('Nome comum').fill('Alface do canteiro')
  await page.getByRole('button', { name: 'Cadastrar espécie', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'O que será plantado?', exact: true })).toBeVisible()
  await expect(page.getByLabel('Área ocupada (m²)')).toHaveValue('3')
  await expect(page.getByRole('combobox', { name: 'O que será plantado *', exact: true }).locator('option:checked')).toHaveText('Alface do canteiro')
  await page.getByRole('button', { name: 'Cadastrar cultivo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Registrar plantio de Alface do canteiro', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Voltar ao canteiro', exact: true }).click()
  await expect(page.getByText('Plantio ainda não registrado', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Registrar plantio', exact: true }).click()
  await expect(page.locator('select[name="cycleId"]')).toHaveCount(0)
  await page.getByLabel('Quantidade plantada').fill('20')
  await page.getByRole('button', { name: 'Registrar plantio', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Canteiro da entrada', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alface do canteiro', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /^20 plantas/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: /^20 plantas/ })).toBeVisible()
  const crops = await (await request.get(`${api()}${prefix}/cultivation-cycles?bedId=${bed.id}&from=0001-01-01&to=9998-12-31`)).json()
  expect(crops.totalCount).toBe(1)
  expect(crops.items[0].bedId).toBe(bed.id)
  const plantings = await (await request.get(`${api()}${prefix}/plantings?cycleId=${crops.items[0].id}&from=0001-01-01&to=9998-12-31`)).json()
  expect(plantings.totalCount).toBe(1)
  expect(plantings.items[0].plantedQuantity).toBe(20)
  await page.screenshot({ path: 'test-results/bed-cultivation-desktop.png', fullPage: true })
  await page.getByRole('link', { name: /^20 plantas/ }).click()
  await expect(page.getByRole('heading', { name: 'Plantio', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '← Voltar: Canteiro', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Canteiro da entrada', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await noOverflow(page)
  await page.screenshot({ path: 'test-results/bed-cultivation-mobile.png', fullPage: true })
  const other = await post(request, `${prefix}/beds`, { name: 'Outro canteiro' })
  await page.goto(`/hortas/${garden.id}/horta/canteiros/${other.id}/plantar?cycleId=${crops.items[0].id}`)
  await expect(page.getByRole('alert')).toContainText('outro canteiro')
  await expect(page.getByLabel('Quantidade plantada')).toHaveCount(0)
})

