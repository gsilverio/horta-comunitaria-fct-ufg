const api = () => `${process.env.HORTA_E2E_API_URL}/api/v1`
interface RecordIdentity { id: string; version: number }
async function post(request: APIRequestContext, path: string, data: unknown): Promise<RecordIdentity> {
  const response = await request.post(api() + path, { data })
  expect(response.status(), await response.text()).toBe(201)
  return response.json()
}
async function context(request: APIRequestContext) {
  const garden = await post(request, '/gardens', { name: 'Horta para organização' })
  const sector = await post(request, `/gardens/${garden.id}/sectors`, { name: 'Setor norte' })
  return { garden, sector, prefix: `/gardens/${garden.id}` }
}
async function createBed(page: Page, name: string) {
  await page.getByRole('link', { name: 'Novo canteiro', exact: true }).click()
  await page.getByLabel('Nome do canteiro').fill(name)
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Concluir cadastro de ${name}` })).toBeVisible()
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

