test('resposta perdida após salvar área: retoma sem duplicar configuração nem canteiro', async ({ page, request }) => {
  const { garden, sector, prefix } = await context(request)
  await page.goto(`/hortas/${garden.id}/horta/setores/${sector.id}`)
  await createBed(page, 'Canteiro com retomada')
  const bedId = new URL(page.url()).hash.split('?')[0].split('/').at(-1)
  await page.getByLabel('Área cultivável (m²)').fill('8')
  let intercepted = false
  await page.route('**/configurations', async route => {
    if (route.request().method() === 'POST' && !intercepted) {
      intercepted = true
      const response = await route.fetch()
      expect(response.status()).toBe(201)
      await route.abort('failed')
    } else await route.continue()
  })
  await page.getByRole('button', { name: 'Concluir cadastro', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Retomar conclusão', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Área cultivável (m²)')).toBeDisabled()
  await page.getByRole('button', { name: 'Retomar conclusão', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Canteiro com retomada', exact: true })).toBeVisible()
  const configs = await (await request.get(`${api()}${prefix}/beds/${bedId}/configurations`)).json()
  const assignments = await (await request.get(`${api()}${prefix}/beds/${bedId}/sector-assignments`)).json()
  const beds = await (await request.get(`${api()}${prefix}/beds/catalog`)).json()
  expect(configs.totalCount).toBe(1)
  expect(assignments.totalCount).toBe(1)
  expect(beds.totalCount).toBe(1)
})

