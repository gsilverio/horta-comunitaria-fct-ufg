import { test, expect } from '@playwright/test'

test('canteiro no editor conclui mapa, área, espécie, cultivo e plantio sem sair do modo interativo', async ({ page, request }) => {
  const api = `${process.env.HORTA_E2E_API_URL}/api/v1`
  const created = await request.post(`${api}/gardens`, { data: { name: 'Horta estação de cultivo' } })
  expect(created.status()).toBe(201)
  const garden = await created.json() as { id: string }
  const path = `/#/hortas/${garden.id}/horta`
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(path)
  await page.getByRole('button', { name: 'Retangular', exact: true }).click()
  await page.getByRole('button', { name: 'Concluir terreno', exact: true }).click()
  await page.getByRole('button', { name: 'Setor com contorno do terreno', exact: true }).click()
  await page.getByRole('button', { name: 'Concluir setor', exact: true }).click()
  await page.getByRole('button', { name: '+ Retângulo', exact: true }).click()
  const bedShape = page.getByRole('application').getByRole('button', { name: /^Retângulo 2,/ })
  await bedShape.click()
  const menu = page.getByRole('complementary', { name: 'Retângulo 2', exact: true })
  await expect(menu).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await menu.evaluate(element => !!element.closest('.drawing-workspace'))).toBe(true)
  const canvasBounds = await page.locator('.interactive-canvas').boundingBox()
  const menuBounds = await menu.boundingBox()
  if (!canvasBounds || !menuBounds) throw new Error('Desenho e painel devem estar visíveis')
  expect(menuBounds.x).toBeGreaterThan(canvasBounds.x + canvasBounds.width)
  await page.locator('.drawing-workspace').screenshot({ path: 'test-results/species-sidebar-catalog-desktop.png' })
  await expect(menu.getByRole('button', { name: 'Selecionar Alface', exact: true })).toBeVisible()
  await menu.getByRole('button', { name: 'Selecionar Alface', exact: true }).click()
  const photo = menu.getByRole('img', { name: 'Foto ilustrativa de Alface', exact: true })
  await expect(photo).toBeVisible()
  await expect.poll(() => photo.evaluate(image => image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0)).toBe(true)
  const slot = menu.getByRole('listitem').filter({ has: page.getByRole('button', { name: 'Selecionar Alface', exact: true }) })
  await slot.getByText('Créditos da foto', { exact: true }).click()
  await expect(slot.getByText('Foto ilustrativa do grupo; não identifica a cultivar.')).toBeVisible()
  await expect(slot.getByRole('link', { name: 'Origem' })).toHaveAttribute('href', /^https:\/\//)
  await slot.getByText('Créditos da foto', { exact: true }).click()
  const pagination = menu.getByRole('navigation', { name: 'Páginas do catálogo de espécies' })
  await pagination.getByRole('button', { name: 'Próxima' }).click()
  await expect(pagination.getByText('Página 2 de 3')).toBeVisible()
  await expect(menu.getByText('Espécie selecionada', { exact: true })).toBeVisible()
  await menu.getByRole('button', { name: 'Continuar com esta espécie', exact: true }).click()
  await menu.getByRole('button', { name: 'Salvar mapa e continuar', exact: true }).click()
  await expect(menu.getByRole('heading', { name: 'Preparar plantio', exact: true })).toBeVisible()
  await menu.getByLabel('Área real do canteiro (m²)').fill('6')
  await menu.getByLabel('Área deste cultivo (m²)').fill('3')
  await menu.getByLabel('Quantidade de plantas').fill('20')
  await menu.screenshot({ path: 'test-results/planting-sheet-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await menu.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await menu.screenshot({ path: 'test-results/planting-sheet-mobile.png' })
  // Uma resposta perdida é retomada com a mesma operação, sem duplicar o plantio.
  let lostCycle = false
  await page.route('**/api/v1/gardens/*/cultivation-cycles', async route => {
    if (route.request().method() !== 'POST' || lostCycle) return route.continue()
    lostCycle = true; await route.fetch(); await route.abort('failed')
  })
  let lost = false
  await page.route('**/api/v1/gardens/*/plantings', async route => {
    if (route.request().method() !== 'POST' || lost) return route.continue()
    lost = true; await route.fetch(); await route.abort('failed')
  })
  await menu.getByRole('button', { name: 'Confirmar plantio', exact: true }).click()
  await menu.getByRole('button', { name: 'Confirmar tentativa original', exact: true }).click()
  await expect.poll(() => lost).toBe(true)
  await menu.getByRole('button', { name: 'Confirmar tentativa original', exact: true }).click()
  await expect(menu.getByRole('heading', { name: 'Plantio concluído', exact: true })).toBeVisible()
  await menu.getByRole('button', { name: 'Voltar ao desenho', exact: true }).click()
  await page.reload()
  await page.getByRole('application').getByRole('button', { name: /^Retângulo 2,/ }).focus()
  await page.keyboard.press('Enter')
  await menu.getByText('Consultar cultivos e retomar plantios', { exact: true }).click()
  await expect(menu.getByText(/^20 plantas/)).toBeVisible()
  const saved = await (await request.get(`${api}/gardens/${garden.id}/layout`)).json() as { layout: { elements: { role: string; entityId: string }[] } }
  const bedId = saved.layout.elements.find(element => element.role === 'bed')?.entityId
  expect(bedId).toBeTruthy()
  const cycles = await (await request.get(`${api}/gardens/${garden.id}/cultivation-cycles?bedId=${bedId}&from=0001-01-01&to=9998-12-31`)).json() as { totalCount: number }
  const plantings = await (await request.get(`${api}/gardens/${garden.id}/plantings?bedId=${bedId}&from=0001-01-01&to=9998-12-31`)).json() as { totalCount: number }
  expect(cycles.totalCount).toBe(1); expect(plantings.totalCount).toBe(1)
  await menu.getByRole('button', { name: 'Voltar ao mapa', exact: true }).click()
  await page.getByRole('link', { name: 'Ver visão panorâmica', exact: true }).click()
  await expect(page.locator('.garden-scene-life image').first()).toBeVisible()
  await expect(page.locator('[data-sector-soil]')).toHaveCount(1)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.garden-scene').screenshot({ path: 'test-results/sector-cultivated-soil.png' })
  await page.getByRole('button', { name: 'Mostrar limites dos setores' }).click()
  await expect(page.locator('[data-sector-soil]')).toHaveCount(1)
  const panorama = page.getByRole('application', { name: 'Mapa panorâmico interativo da horta' })
  const surface = panorama.getByRole('button', { name: 'Retângulo 2, retângulo', exact: true }).locator(':scope > polygon[fill="url(#garden-scene-bed-texture)"]')
  await panorama.scrollIntoViewIfNeeded()
  const surfaceBox = await surface.boundingBox()
  if (!surfaceBox) throw new Error('Superfície do canteiro ausente')
  // As plantas têm animação contínua; o ponteiro real seleciona pela superfície.
  await page.mouse.click(surfaceBox.x + surfaceBox.width / 2, surfaceBox.y + surfaceBox.height / 2)
  await expect(panorama).toHaveAttribute('data-camera-moving', 'false')
  await page.getByRole('link', { name: 'Ver detalhes do canteiro' }).click()
  await expect(page.getByRole('heading', { name: 'Retângulo 2', exact: true })).toBeVisible()
  await expect(page.getByText('Código do canteiro', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Alface', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /^20 plantas/ })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar à panorâmica', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Visão panorâmica da horta' })).toBeVisible()
})

test('ficha de plantio retoma cultivo salvo após rejeição do plantio sem duplicar o ciclo', async ({ page, request }) => {
  const api = `${process.env.HORTA_E2E_API_URL}/api/v1`
  const garden = await (await request.post(`${api}/gardens`, { data: { name: 'Horta com plantio a revisar' } })).json() as { id: string }
  const layout = await request.put(`${api}/gardens/${garden.id}/layout`, { data: { operationId: crypto.randomUUID(), expectedVersion: 0, layout: { width: 20, height: 20, boundary: [{ x: 0, y: 0 }, { x: 20, y: 0 }, { x: 20, y: 20 }, { x: 0, y: 20 }], elements: [{ id: 's', name: 'Setor', role: 'sector', shape: 'rectangle', x: 0, y: 0, width: 20, height: 20, rotationDeg: 0 }, { id: 'b', name: 'Canteiro de revisão', role: 'bed', shape: 'rectangle', x: 5, y: 5, width: 2, height: 1, rotationDeg: 0, sectorId: 's' }] } } })
  expect(layout.ok()).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`/#/hortas/${garden.id}/horta`)
  await page.getByRole('application').getByRole('button', { name: /^Canteiro de revisão,/ }).click()
  const menu = page.getByRole('complementary', { name: 'Canteiro de revisão', exact: true })
  await menu.getByRole('button', { name: 'Selecionar Alface', exact: true }).click()
  await menu.getByRole('button', { name: 'Continuar com esta espécie' }).click()
  await menu.getByLabel('Área real do canteiro (m²)').fill('6')
  await menu.getByLabel('Área deste cultivo (m²)').fill('3')
  await menu.getByLabel('Quantidade de plantas').fill('10')
  await page.route('**/api/v1/gardens/*/plantings', route => route.request().method() === 'POST' ? route.fulfill({ status: 400, json: { title: 'Revise o plantio', errors: { plantedQuantity: ['Quantidade precisa ser revisada.'] } } }) : route.continue())
  await menu.getByRole('button', { name: 'Confirmar plantio', exact: true }).click()
  await expect(menu.getByRole('button', { name: 'Confirmar plantio', exact: true })).toBeDisabled()
  await menu.getByRole('button', { name: 'Revisar plantio do cultivo salvo' }).click()
  await page.unroute('**/api/v1/gardens/*/plantings')
  await menu.getByLabel('Quantidade plantada').fill('10')
  await menu.getByRole('button', { name: 'Registrar plantio', exact: true }).click()
  await expect(menu.getByRole('heading', { name: 'Plantio concluído' })).toBeVisible()
  const cycles = await (await request.get(`${api}/gardens/${garden.id}/cultivation-cycles?from=0001-01-01&to=9998-12-31`)).json() as { totalCount: number }
  const plantings = await (await request.get(`${api}/gardens/${garden.id}/plantings?from=0001-01-01&to=9998-12-31`)).json() as { totalCount: number }
  expect(cycles.totalCount).toBe(1); expect(plantings.totalCount).toBe(1)
})
